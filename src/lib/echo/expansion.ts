/** 扩展命中的权重折扣：低于原文直接命中，避免扩展结果盖过真实线索。 */
export const EXPANSION_WEIGHT = 0.45;

export interface AppliedExpansion {
  /** 用户原文里出现的词 */
  from: string;
  /** 关联到的目录检索词 */
  targets: string[];
}

/**
 * 在查询里找出所有可扩展的词。
 * 长词优先：如果同时命中「太阳雨」和「雨」，只用更具体的那个，避免重复计分。
 */
export function expandQuery(query: string): AppliedExpansion[] {
  const text = query.trim();
  if (!text) return [];

  const applied: AppliedExpansion[] = [];
  const claimed = new Set<string>();

  const keys = Object.keys(TERM_EXPANSIONS).sort(
    (a, b) => Array.from(b).length - Array.from(a).length,
  );

  for (const key of keys) {
    if (!text.includes(key)) continue;
    // 这个词已经被更具体的词覆盖了（例如「太阳雨」已包含「雨」）
    if (claimed.has(key)) continue;

    const targets = TERM_EXPANSIONS[key] ?? [];
    if (targets.length === 0) continue;

    applied.push({ from: key, targets });
    claimed.add(key);
    for (const target of targets) claimed.add(target);
  }

  return applied;
}
